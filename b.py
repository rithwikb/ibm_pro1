import numpy as np
import matplotlib.pyplot as plt

x = np.linspace(-10, 10, 500)
y = x + x**2 + x**3

def new_function(x):
    return x + x**2 + np.sin(x)**3

def generate_and_display_graph():
    plt.figure(figsize=(10, 6))
    plt.plot(x, x + x**2 + np.sin(x)**3, label='y = x + x$^2$ + sin$^3$(x)')
    plt.xlabel('x')
    plt.ylabel('y')
    plt.title('Graph of y = x + x$^2$ + sin$^3$(x)')
    plt.legend()
    plt.grid(True)
    plt.tight_layout()
    plt.show()

if __name__ == "__main__":
    generate_and_display_graph()




































































































































































































































































